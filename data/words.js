/** 겹치지 않게 뽑기: 전부 한 번씩 섞어 쓰고, 다 쓰면 다시 섞되 방금 나온 것들은 맨 뒤로 (서버 전체가 함께 써요 → 방이 바뀌어도 연달아 겹치지 않아요) */
function deck(list, keep = 60) {
  let bag = [];
  const recent = [];
  return () => {
    if (!bag.length) {
      const rs = new Set(recent), all = shuffle(list);
      bag = [...all.filter(w => !rs.has(w)), ...all.filter(w => rs.has(w))];
    }
    const w = bag.shift();
    recent.push(w); if (recent.length > Math.min(keep, list.length - 1)) recent.shift();
    return w;
  };
}
